// Version identifies the generator release.
const Version = "0.3.0"

// Marker identifies files owned by the generator.
const Marker = "Code generated by wasmbind. DO NOT EDIT."

// Limits bounds startup, concurrency, and copied values.
type Limits struct {
	StartupTimeoutMs int `json:"startupTimeoutMs"`
	MaxPendingCalls  int `json:"maxPendingCalls"`
	MaxResources     int `json:"maxResources"`
	MaxValueBytes    int `json:"maxValueBytes"`
	MaxValueDepth    int `json:"maxValueDepth"`
	MaxElements      int `json:"maxElements"`
}

// Defaults contains the version-one bridge limits.
var Defaults = Limits{30000, 256, 1024, 16 << 20, 64, 1000000}

// Type describes a supported Go value and its JavaScript representation.
type Type struct {
	Input  bool   `json:"input,omitempty"`
	Kind   string `json:"kind"`
	Name   string `json:"name,omitempty"`
	Length int64  `json:"length,omitempty"`
	Elem   *Type  `json:"elem,omitempty"`
	Go     string `json:"-"`
}

// Field describes an explicitly copied record field.
type Field struct {
	Name     string `json:"name"`
	GoName   string `json:"goName"`
	Type     *Type  `json:"type"`
	Doc      string `json:"doc,omitempty"`
	Optional bool   `json:"optional,omitempty"`
	Default  string `json:"default,omitempty"`
}

// Constant describes one exported typed Go constant in an enum object.
type Constant struct {
	Name   string `json:"name"`
	GoName string `json:"goName"`
	Value  string `json:"value"`
	Doc    string `json:"doc,omitempty"`
}

// Decl describes an annotated binding type.
type Variant struct {
	Constant string   `json:"constant"`
	GoName   string   `json:"goName"`
	Value    string   `json:"value"`
	Fields   []string `json:"fields"`
}

type Decl struct {
	Input         bool      `json:"input,omitempty"`
	Brand         bool      `json:"brand,omitempty"`
	Discriminant  string    `json:"discriminant,omitempty"`
	Variants      []Variant `json:"variants,omitempty"`
	unionSpec     string
	variantSpec   string
	Concurrent    bool             `json:"concurrent,omitempty"`
	Value         *Type            `json:"value,omitempty"`
	Constants     []Constant       `json:"constants,omitempty"`
	Validate      string           `json:"validate,omitempty"`
	Optional      bool             `json:"optional,omitempty"`
	Default       string           `json:"default,omitempty"`
	Kind          string           `json:"kind"`
	Name          string           `json:"name"`
	GoName        string           `json:"goName"`
	Doc           string           `json:"doc,omitempty"`
	Position      string           `json:"position"`
	Fields        []Field          `json:"fields,omitempty"`
	Close         string           `json:"close,omitempty"`
	CloseError    bool             `json:"closeError,omitempty"`
	Methods       map[string]*Call `json:"methods,omitempty"`
	Domain        string           `json:"domain,omitempty"`
	ImportMethods []*Call          `json:"importMethods,omitempty"`
	Order         int              `json:"-"`
}

// Param describes one JavaScript-visible argument.
type Param struct {
	Name string `json:"name"`
	Type *Type  `json:"type"`
}

// Call describes one concrete asynchronous export.
type Call struct {
	Scalar     string   `json:"scalar,omitempty"`
	Namespace  string   `json:"namespace,omitempty"`
	Owned      bool     `json:"owned,omitempty"`
	NonNull    bool     `json:"nonNull,omitempty"`
	Op         string   `json:"op,omitempty"`
	ID         int      `json:"id"`
	TypeArgs   []string `json:"typeArgs,omitempty"`
	Name       string   `json:"name"`
	GoName     string   `json:"goName"`
	Receiver   string   `json:"receiver,omitempty"`
	ReceiverGo string   `json:"-"`
	Context    bool     `json:"context,omitempty"`
	Params     []Param  `json:"params"`
	Result     *Type    `json:"result,omitempty"`
	Error      bool     `json:"error,omitempty"`
	Doc        string   `json:"doc,omitempty"`
	Position   string   `json:"position"`
}

// Manifest records the schema and optional build provenance.
type Manifest struct {
	Naming              string            `json:"naming,omitempty"`
	TypeScriptMinTested string            `json:"typescriptMinTested"`
	ABI                 *ABIProtocol      `json:"abi,omitempty"`
	Features            []string          `json:"features,omitempty"`
	Backend             string            `json:"backend"`
	Protocols           map[string]int    `json:"protocols,omitempty"`
	Init                *Call             `json:"init,omitempty"`
	Generated           string            `json:"generated"`
	SchemaVersion       int               `json:"schemaVersion"`
	GeneratorVersion    string            `json:"generatorVersion"`
	Package             string            `json:"package"`
	Declarations        []*Decl           `json:"declarations"`
	Calls               []*Call           `json:"calls"`
	Limits              Limits            `json:"limits"`
	Fingerprint         string            `json:"fingerprint"`
	BuildIdentity       string            `json:"buildIdentity,omitempty"`
	Compiler            string            `json:"compiler,omitempty"`
	Tags                string            `json:"tags,omitempty"`
	Artifacts           map[string]string `json:"artifacts,omitempty"`
}

// API contains the validated schema and its loaded Go package.
type API struct {
	Manifest
	Pkg       *packages.Package
	Dir       string
	ModuleDir string
	Imports   map[string]string
}

type identifierValidator struct{}

var ident identifierValidator

func (identifierValidator) MatchString(s string) bool {
	if s == "" {
		return false
	}
	for i, r := range s {
		start := r == '_' || r == '$' || unicode.IsLetter(r) || unicode.Is(unicode.Nl, r) || unicode.Is(unicode.Other_ID_Start, r)
		rest := start || unicode.Is(unicode.Mn, r) || unicode.Is(unicode.Mc, r) || unicode.Is(unicode.Nd, r) || unicode.Is(unicode.Pc, r) || unicode.Is(unicode.Other_ID_Continue, r) || r == '\u200c' || r == '\u200d'
		if !rest || (i == 0 && !start) {
			return false
		}
	}
	return true
}

var reserved = map[string]bool{"load": true, "dispose": true, "then": true, "asyncDispose": true, "constructor": true, "__proto__": true}

func validName(s string) bool { return ident.MatchString(s) && !reserved[s] }

type loader struct {
	current          string
	api              *API
	named            map[*types.TypeName]*Decl
	visiting         map[*types.TypeName]bool
	scopes           map[string]map[string]bool
	features         map[string]bool
	docs             map[token.Pos]string
	methodDirectives map[token.Pos]map[string]string
}

// Load type-checks one package and validates its annotated declarations.
func Load(ctx context.Context, pattern, tags string) (*API, error) {
	return LoadOptions(ctx, pattern, tags, "", "syscalljs")
}

// LoadOptions validates an API with explicitly enabled features and backend.
func LoadOptions(ctx context.Context, pattern, tags, features, backend string) (*API, error) {
	enabled, featureList, err := parseFeatures(features)
	if err != nil {
		return nil, err
	}
	if backend != "syscalljs" && backend != "abi" {
		return nil, fmt.Errorf("unknown backend %q", backend)
	}
	if backend == "abi" && len(enabled) > 0 {
		return nil, fmt.Errorf("abi feature combinations are not qualified; use syscalljs or disable features")
	}

	flags := []string{"-mod=readonly"}
	if tags != "" {
		flags = append(flags, "-tags="+tags)
	}
	env := append(os.Environ(), "GOOS=js", "GOARCH=wasm")
	dir := ""
	if filepath.IsAbs(pattern) {
		if info, err := os.Stat(pattern); err == nil && info.IsDir() {
			dir = pattern
			pattern = "."
		}
	}
	ps, err := packages.Load(&packages.Config{Context: ctx, Dir: dir, Env: env, BuildFlags: flags, Mode: packages.NeedName | packages.NeedFiles | packages.NeedCompiledGoFiles | packages.NeedSyntax | packages.NeedTypes | packages.NeedTypesInfo | packages.NeedImports | packages.NeedDeps | packages.NeedModule | packages.NeedEmbedFiles}, pattern)
	if err != nil {
		return nil, fmt.Errorf("load package: %w", err)
	}
	if len(ps) != 1 {
		return nil, fmt.Errorf("expected exactly one package, got %d", len(ps))
	}
	p := ps[0]
	var problems []string
	packages.Visit(ps, nil, func(p *packages.Package) {
		for _, e := range p.Errors {
			problems = append(problems, e.Error())
		}
	})
	if len(problems) > 0 {
		sort.Strings(problems)
		return nil, fmt.Errorf("%s", strings.Join(problems, "\n"))
	}
	if p.Name == "main" {
		return nil, fmt.Errorf("%s: main packages cannot be bound; use a narrow wrapper package", p.PkgPath)
	}
	if len(p.GoFiles) == 0 || p.Module == nil {
		return nil, fmt.Errorf("input must belong to a module")
	}
	a := &API{Manifest: Manifest{Generated: Marker, SchemaVersion: 1, GeneratorVersion: Version, TypeScriptMinTested: "6.0.3", Package: p.PkgPath, Backend: backend, Features: featureList, Limits: Defaults, Declarations: []*Decl{}, Calls: []*Call{}}, Pkg: p, Dir: filepath.Dir(p.GoFiles[0]), ModuleDir: p.Module.Dir, Imports: map[string]string{p.PkgPath: "api"}}
	l := &loader{api: a, named: map[*types.TypeName]*Decl{}, visiting: map[*types.TypeName]bool{}, scopes: map[string]map[string]bool{}, features: enabled, docs: map[token.Pos]string{}, methodDirectives: map[token.Pos]map[string]string{}}
	if err := l.packagePolicy(); err != nil {
		return nil, err
	}
	// Collect annotations before resolving references so file order is irrelevant.
	for _, f := range p.Syntax {
		for _, node := range f.Decls {
			g, ok := node.(*ast.GenDecl)
			if !ok {
				continue
			}
			for _, s := range g.Specs {
				ts, ok := s.(*ast.TypeSpec)
				if !ok {
					if v, ok := s.(*ast.ValueSpec); ok {
						doc := v.Doc
						if doc == nil {
							doc = g.Doc
						}
						ds, _, err := directives(doc)
						if err != nil || (len(ds) > 0 && (len(ds) != 1 || !hasDirective(ds, "member") || g.Tok != token.CONST || len(v.Names) != 1)) {
							return nil, l.diag(v.Pos(), v.Names[0].Name, "annotations on variables and constants are unsupported")
						}
					}
					continue
				}
				l.current = ts.Name.Name
				doc := ts.Doc
				if doc == nil {
					doc = g.Doc
				}
				ds, text, err := directives(doc)
				if err != nil {
					return nil, l.diag(ts.Pos(), ts.Name.Name, err.Error())
				}
				if len(ds) == 0 {
					continue
				}
				unionSpec := ds["union"]
				delete(ds, "union")
				variantSpec := ds["variant"]
				delete(ds, "variant")
				concurrent, hasConcurrent := ds["concurrent"]
				delete(ds, "concurrent")
				validate, hasValidate := ds["validate"]
				delete(ds, "validate")
				brand, hasBrand := ds["brand"]
				delete(ds, "brand")
				optional, hasOptional := ds["optional"]
				delete(ds, "optional")
				if len(ds) != 1 {
					return nil, l.diag(ts.Pos(), ts.Name.Name, "contradictory directives")
				}
				obj := p.TypesInfo.Defs[ts.Name].(*types.TypeName)
				if !obj.Exported() || obj.IsAlias() {
					return nil, l.diag(ts.Pos(), obj.Name(), "annotations require a public defined type")
				}
				n := obj.Type().(*types.Named)
				if n.TypeParams().Len() != 0 {
					return nil, l.diag(ts.Pos(), obj.Name(), "generic declarations are unsupported")
				}
				if _, ok := n.Underlying().(*types.Struct); !ok && ds["imports"] == "" && ds["scalar"] == "" && ds["enum"] == "" {
					return nil, l.diag(ts.Pos(), obj.Name(), "record and resource annotations require structs")
				}
				d := &Decl{Brand: hasBrand, unionSpec: unionSpec, variantSpec: variantSpec, Concurrent: hasConcurrent, Validate: validate, Optional: hasOptional, Default: optional, GoName: obj.Name(), Name: obj.Name(), Doc: text, Position: l.position(ts.Pos()), Order: len(a.Declarations)}
				if v, ok := ds["scalar"]; ok {
					d.Kind = "scalar"
					d.Name = v
				} else if v, ok := ds["enum"]; ok {
					d.Kind = "enum"
					d.Name = v
				} else if v, ok := ds["record"]; ok {
					if v != "" {
						return nil, l.diag(ts.Pos(), obj.Name(), "record directive takes no name")
					}
					d.Kind = "record"
				} else if v, ok := ds["resource"]; ok {
					d.Kind = "resource"
					d.Name = v
				} else if v, ok := ds["error"]; ok {
					if !enabled["errors"] {
						return nil, l.diag(ts.Pos(), obj.Name(), "error directive requires -features errors")
					}
					d.Kind = "error"
					d.Name = v
					d.Domain = p.PkgPath + "." + obj.Name()
					if !types.Implements(types.NewPointer(n), types.Universe.Lookup("error").Type().Underlying().(*types.Interface)) {
						return nil, l.diag(ts.Pos(), obj.Name(), "*T must implement error")
					}
				} else if v, ok := ds["imports"]; ok {
					if !enabled["imports"] {
						return nil, l.diag(ts.Pos(), obj.Name(), "imports directive requires -features imports")
					}
					d.Kind = "imports"
					d.Name = v
					if _, ok := n.Underlying().(*types.Interface); !ok {
						return nil, l.diag(ts.Pos(), obj.Name(), "imports directive requires an interface")
					}
				} else {
					return nil, l.diag(ts.Pos(), obj.Name(), "type requires record, resource, error, or imports directive")
				}
				if (unionSpec != "" || variantSpec != "") && d.Kind != "record" {
					return nil, l.diag(ts.Pos(), obj.Name(), "union and variant require record")
				}
				if hasConcurrent && (d.Kind != "resource" || concurrent != "") {
					return nil, l.diag(ts.Pos(), obj.Name(), "concurrent takes no arguments and requires a resource")
				}
				if (hasValidate && d.Kind != "scalar" && d.Kind != "enum") || (hasOptional && d.Kind != "imports") {
					return nil, l.diag(ts.Pos(), obj.Name(), "validate requires scalar or enum; optional requires imports")
				}
				if hasBrand && (brand != "" || d.Kind != "scalar" || !hasValidate) {
					return nil, l.diag(ts.Pos(), obj.Name(), "brand takes no arguments and requires a validated scalar")
				}
				if d.Kind == "enum" && hasValidate {
					if validate != "" {
						return nil, l.diag(ts.Pos(), obj.Name(), "enum validate takes no function")
					}
					d.Validate = "enum"
				}
				if d.Kind == "scalar" && hasValidate && validate == "" {
					return nil, l.diag(ts.Pos(), obj.Name(), "scalar validate requires a validator function")
				}
				if err := l.name("types", d.Name, ts.Pos(), obj.Name()); err != nil {
					return nil, err
				}
				l.named[obj] = d
				a.Declarations = append(a.Declarations, d)
			}
		}
	}
	if err := l.scalars(); err != nil {
		return nil, err
	}
	// Validate all records, including records unused by functions.
	sort.Slice(a.Declarations, func(i, j int) bool { return a.Declarations[i].Name < a.Declarations[j].Name })
	for _, d := range a.Declarations {
		if d.Kind == "error" {
			obj := p.Types.Scope().Lookup(d.GoName)
			if d.Name == "AbortError" {
				return nil, l.diag(obj.Pos(), d.GoName, "domain error name matches bridge error")
			}
			for _, name := range []string{d.Name + "Data", "is" + d.Name} {
				if err := l.name("types", name, obj.Pos(), d.GoName); err != nil {
					return nil, err
				}
			}
		}
	}
	for _, d := range a.Declarations {
		obj := p.Types.Scope().Lookup(d.GoName).(*types.TypeName)
		l.current = d.GoName
		if d.Kind == "record" || d.Kind == "error" {
			if _, err := l.value(obj.Type(), obj.Pos()); err != nil {
				return nil, err
			}
		}
	}
	if err := l.unions(); err != nil {
		return nil, err
	}
	if err := l.imports(); err != nil {
		return nil, err
	}
	for _, f := range p.Syntax {
		for _, node := range f.Decls {
			fd, ok := node.(*ast.FuncDecl)
			if !ok {
				continue
			}
			l.current = fd.Name.Name
			ds, text, err := directives(fd.Doc)
			if err != nil {
				return nil, l.diag(fd.Pos(), fd.Name.Name, err.Error())
			}
			if len(ds) == 0 {
				continue
			}
			obj := p.TypesInfo.Defs[fd.Name].(*types.Func)
			sig := obj.Type().(*types.Signature)
			if !obj.Exported() {
				return nil, l.diag(fd.Pos(), obj.Name(), "exports must be public")
			}
			namespace, hasNamespace := ds["namespace"]
			delete(ds, "namespace")
			constructor, hasConstructor := ds["constructor"]
			delete(ds, "constructor")
			if hasNamespace && hasConstructor {
				return nil, l.diag(fd.Pos(), obj.Name(), "namespace and constructor are mutually exclusive")
			}
			if hasConstructor {
				namespace = constructor
			}
			if (hasNamespace || hasConstructor) && (sig.Recv() != nil || namespace == "" || !validName(namespace)) {
				return nil, l.diag(fd.Pos(), obj.Name(), "namespace and constructor require a free export and valid name")
			}
			nonNull, hasNonNull := ds["nonnull"]
			delete(ds, "nonnull")
			owned, hasOwned := ds["owned"]
			delete(ds, "owned")
			if hasOwned && (owned != "" || len(ds) != 1 || !hasDirective(ds, "export") || sig.Recv() == nil) {
				return nil, l.diag(fd.Pos(), obj.Name(), "owned requires an exported resource receiver method and takes no argument")
			}
			if hasNonNull && (nonNull != "" || len(ds) != 1 || !hasDirective(ds, "export")) {
				return nil, l.diag(fd.Pos(), obj.Name(), "nonnull requires export and takes no argument")
			}
			if len(ds) != 1 {
				return nil, l.diag(fd.Pos(), obj.Name(), "contradictory directives")
			}
			var resource *Decl
			if sig.Recv() != nil {
				ptr, ok := sig.Recv().Type().(*types.Pointer)
				if !ok {
					return nil, l.diag(fd.Pos(), obj.Name(), "resource methods require a pointer receiver")
				}
				n, ok := ptr.Elem().(*types.Named)
				if ok {
					resource = l.named[n.Obj()]
				}
				if resource == nil || resource.Kind != "resource" {
					return nil, l.diag(fd.Pos(), obj.Name(), "receiver must be an annotated resource")
				}
			}
			if v, ok := ds["close"]; ok {
				if v != "" || sig.TypeParams().Len() != 0 || resource == nil || sig.Params().Len() != 0 || sig.Results().Len() > 1 || (sig.Results().Len() == 1 && !isError(sig.Results().At(0).Type())) || sig.Variadic() {
					return nil, l.diag(fd.Pos(), obj.Name(), "close requires a resource method with no arguments and no result or error")
				}
				if resource.Close != "" {
					return nil, l.diag(fd.Pos(), obj.Name(), "duplicate close method")
				}
				resource.Close = obj.Name()
				resource.CloseError = sig.Results().Len() == 1
				continue
			}
			if _, ok := ds["init"]; ok {
				if err := l.initializer(obj, sig, fd.Pos(), ds["init"]); err != nil {
					return nil, err
				}
				continue
			}
			handled, err := l.extensionMethod(obj, sig, resource, fd.Pos(), ds, text)
			if err != nil {
				return nil, err
			}
			if handled {
				continue
			}
			names, ok := ds["export"]
			if !ok {
				return nil, l.diag(fd.Pos(), obj.Name(), "function requires export or close directive")
			}
			for _, export := range strings.Split(names, "\n") {
				name, args, err := specialization(export)
				if name == "" {
					name = l.memberName(obj.Name())
				}
				if err != nil {
					return nil, l.diag(fd.Pos(), obj.Name(), err.Error())
				}
				sig := obj.Type().(*types.Signature)
				var goArgs []string
				if len(args) > 0 {
					var ts []types.Type
					for _, expr := range args {
						tv, e := types.Eval(p.Fset, p.Types, fd.Pos(), expr)
						if e != nil || !tv.IsType() {
							return nil, l.diag(fd.Pos(), obj.Name(), "invalid type argument "+expr)
						}
						ts = append(ts, tv.Type)
						goArgs = append(goArgs, l.goType(tv.Type))
					}
					inst, e := types.Instantiate(types.NewContext(), sig, ts, true)
					if e != nil {
						return nil, l.diag(fd.Pos(), obj.Name(), e.Error())
					}
					sig = inst.(*types.Signature)
				}
				c := &Call{Owned: hasOwned, Namespace: namespace, NonNull: hasNonNull, TypeArgs: goArgs, Name: name, GoName: obj.Name(), Doc: text, Position: l.position(fd.Pos()), Params: []Param{}}
				if resource != nil {
					c.Receiver = resource.Name
					c.ReceiverGo = resource.GoName
				}
				scope := c.Receiver
				if namespace != "" {
					scope = "namespace:" + namespace
				}
				if err := l.name(scope, name, fd.Pos(), obj.Name()); err != nil {
					return nil, err
				}
				if sig.Variadic() || sig.TypeParams().Len() != 0 {
					return nil, l.diag(fd.Pos(), obj.Name(), "variadic functions and unspecialized generics are unsupported; specify export name[Type, ...]")
				}
				for i := 0; i < sig.Params().Len(); i++ {
					v := sig.Params().At(i)
					if i == 0 && isContext(v.Type()) {
						c.Context = true
						continue
					}
					t, err := l.value(v.Type(), v.Pos())
					if err != nil {
						return nil, err
					}
					pn := v.Name()
					if !ident.MatchString(pn) {
						pn = fmt.Sprintf("arg%d", i)
					}
					if containsDomain(l, t) {
						return nil, l.diag(v.Pos(), obj.Name(), "domain errors cannot be ordinary values")
					}
					c.Params = append(c.Params, Param{pn, t})
				}
				r := sig.Results()
				n := r.Len()
				if n > 0 && isError(r.At(n-1).Type()) {
					c.Error = true
					n--
				}
				if n > 1 {
					return nil, l.diag(fd.Pos(), obj.Name(), "only no result, T, error, or (T, error) is supported")
				}
				if n == 1 {
					c.Result, err = l.value(r.At(0).Type(), r.At(0).Pos())
					if err == nil && containsDomain(l, c.Result) {
						return nil, l.diag(r.At(0).Pos(), obj.Name(), "domain errors cannot be ordinary values")
					}
					if err != nil {
						return nil, err
					}
				}
				if hasNonNull && (c.Result == nil || c.Result.Kind != "pointer" && c.Result.Kind != "resource") {
					return nil, l.diag(fd.Pos(), obj.Name(), "nonnull requires a pointer or resource result")
				}
				if hasConstructor && (c.Result == nil || c.Result.Kind != "resource" || c.Result.Name != namespace) {
					return nil, l.diag(fd.Pos(), obj.Name(), "constructor requires a result of its named resource")
				}
				if hasOwned && (c.Result == nil || !containsResource(c.Result)) {
					return nil, l.diag(fd.Pos(), obj.Name(), "owned requires a resource result or collection of resources")
				}
				a.Calls = append(a.Calls, c)
			}
		}
	}
	for _, d := range a.Declarations {
		if !d.Brand {
			continue
		}
		obj := p.Types.Scope().Lookup(d.GoName)
		if err := l.name("types", d.Name+"Brand", obj.Pos(), d.GoName); err != nil {
			return nil, err
		}
		name := "parse" + d.Name
		if err := l.name("", name, obj.Pos(), d.GoName); err != nil {
			return nil, err
		}
		result, err := l.value(obj.Type(), obj.Pos())
		if err != nil {
			return nil, err
		}
		a.Calls = append(a.Calls, &Call{Name: name, GoName: d.GoName, Scalar: d.GoName, Context: true, Params: []Param{{Name: "value", Type: d.Value}}, Result: result, Position: d.Position, Doc: "Validates value and returns a " + d.Name + "."})
	}
	if err := l.namespaces(); err != nil {
		return nil, err
	}
	if err := l.finishExtensions(); err != nil {
		return nil, err
	}
	if err := l.inputs(); err != nil {
		return nil, err
	}
	for _, d := range a.Declarations {
		if d.Kind == "resource" && d.Close == "" {
			return nil, fmt.Errorf("%s: %s: resource requires exactly one annotated close method", d.Position, d.GoName)
		}
	}
	sort.Slice(a.Declarations, func(i, j int) bool { return a.Declarations[i].Name < a.Declarations[j].Name })
	sort.Slice(a.Calls, func(i, j int) bool {
		x, y := a.Calls[i], a.Calls[j]
		if x.Receiver != y.Receiver {
			return x.Receiver < y.Receiver
		}
		if x.Namespace != y.Namespace {
			return x.Namespace < y.Namespace
		}
		return x.Name < y.Name
	})
	for i, c := range a.Calls {
		c.ID = i
	}
	if len(enabled) > 0 {
		a.Protocols = map[string]int{}
		for k := range enabled {
			a.Protocols[k] = 1
		}
	}
	if backend == "abi" {
		a.Protocols = map[string]int{"abi": 1}
		a.ABI = &ABIProtocol{MaxBufferBytes: 32 << 20, Tags: map[string]int{"null": 1, "bool": 2, "float": 3, "string": 4, "bytes": 5, "array": 6, "record": 7, "resource": 8, "int": 9, "uint": 10}, QualifiedFeatures: []string{}}
	}
	b, _ := json.Marshal(a.Manifest)
	h := sha256.Sum256(b)
	a.Fingerprint = hex.EncodeToString(h[:])
	return a, nil
}
func directives(g *ast.CommentGroup) (map[string]string, string, error) {
	d := map[string]string{}
	if g == nil {
		return d, "", nil
	}
	var text []string
	for _, c := range g.List {
		s := strings.TrimSpace(strings.TrimPrefix(c.Text, "//"))
		if strings.HasPrefix(s, "wasmbind:") {
			p := strings.Fields(strings.TrimPrefix(s, "wasmbind:"))
			if len(p) < 1 || len(p) > 2 {
				return nil, "", fmt.Errorf("malformed wasmbind directive")
			}
			k := p[0]
			if !knownDirective(k) {
				return nil, "", fmt.Errorf("unknown directive %q", k)
			}
			v := ""
			if len(p) == 2 {
				v = p[1]
			}
			if old, ok := d[k]; ok {
				if k != "export" && k != "variant" {
					return nil, "", fmt.Errorf("duplicate directive %q", k)
				}
				v = old + "\n" + v
			}
			d[k] = v
		} else {
			text = append(text, s)
		}
	}
	return d, strings.TrimSpace(strings.Join(text, "\n")), nil
}
func (l *loader) position(pos token.Pos) string {
	p := l.api.Pkg.Fset.Position(pos)
	rel, _ := filepath.Rel(l.api.Dir, p.Filename)
	return fmt.Sprintf("%s:%d:%d", filepath.ToSlash(rel), p.Line, p.Column)
}
func (l *loader) diag(pos token.Pos, name, msg string) error {
	if l.current != "" && l.current != name {
		name = l.current + ": " + name
	}
	return fmt.Errorf("%s: %s: %s; use a narrow supported wrapper", l.position(pos), name, msg)
}
func (l *loader) name(scope, name string, pos token.Pos, goName string) error {
	if !validName(name) || (scope == "types" && (strings.Contains(" break case catch class const continue debugger default delete do else enum export extends false finally for function if import in instanceof new null return super switch this throw true try typeof var void while with implements interface let package private protected public static yield await type declare namespace module abstract as asserts any boolean constructor infer is keyof never number object readonly require string symbol unknown from get set of ", " "+name+" ") || name == "Imports" || name == "resourceBrand" || name == "Module" || name == "CallOptions" || name == "LoadOptions" || name == "WasmBindError")) {
		return l.diag(pos, goName, "invalid or reserved JavaScript name "+fmt.Sprintf("%q", name))
	}
	if l.scopes[scope] == nil {
		l.scopes[scope] = map[string]bool{}
	}
	if l.scopes[scope][name] {
		return l.diag(pos, goName, "duplicate JavaScript name "+name)
	}
	l.scopes[scope][name] = true
	return nil
}
func isError(t types.Type) bool { return types.Identical(t, types.Universe.Lookup("error").Type()) }
func isContext(t types.Type) bool {
	n, ok := types.Unalias(t).(*types.Named)
	return ok && n.Obj().Pkg() != nil && n.Obj().Pkg().Path() == "context" && n.Obj().Name() == "Context"
}
func (l *loader) goType(t types.Type) string {
	return types.TypeString(t, func(p *types.Package) string {
		if p == nil {
			return ""
		}
		if n := l.api.Imports[p.Path()]; n != "" {
			return n
		}
		hash := sha256.Sum256([]byte(p.Path()))
		n := fmt.Sprintf("pkg%x", hash[:4])
		l.api.Imports[p.Path()] = n
		return n
	})
}
func (l *loader) value(t types.Type, pos token.Pos) (*Type, error) {
	t = types.Unalias(t)
	out := &Type{Go: l.goType(t)}
	switch t := t.(type) {
	case *types.Named:
		if t.TypeArgs().Len() != 0 {
			break
		}
		if !t.Obj().Exported() {
			return nil, l.diag(pos, t.String(), "named binding types must be public")
		}
		if d := l.named[t.Obj()]; d != nil {
			if d.Kind == "scalar" || d.Kind == "enum" {
				u, err := l.value(t.Underlying(), pos)
				if err != nil {
					return nil, err
				}
				u.Name = d.Name
				u.Go = out.Go
				return u, nil
			}
			if d.Kind != "record" && d.Kind != "error" {
				break
			}
			if l.visiting[t.Obj()] {
				return nil, l.diag(pos, t.String(), "recursive record graph")
			}
			out.Kind = "record"
			out.Name = d.Name
			if d.Fields != nil {
				return out, nil
			}
			l.visiting[t.Obj()] = true
			defer delete(l.visiting, t.Obj())
			d.Fields = []Field{}
			st := t.Underlying().(*types.Struct)
			seen := map[string]bool{}
			for i := 0; i < st.NumFields(); i++ {
				f := st.Field(i)
				tag := reflect.StructTag(st.Tag(i)).Get("wasmbind")
				if tag == "-" {
					continue
				}
				if !f.Exported() || f.Embedded() {
					return nil, l.diag(f.Pos(), f.Name(), "private and embedded record fields are unsupported")
				}
				name := l.memberName(f.Name())
				parts := strings.Split(tag, ",")
				optional := false
				if parts[0] != "" {
					name = parts[0]
				}
				for _, option := range parts[1:] {
					if option != "optional" || optional {
						return nil, l.diag(f.Pos(), f.Name(), "unknown or duplicate record field option")
					}
					optional = true
				}
				if !validName(name) || seen[name] {
					return nil, l.diag(f.Pos(), f.Name(), "invalid, reserved, or duplicate record field name")
				}
				seen[name] = true
				ft, err := l.value(f.Type(), f.Pos())
				if err != nil {
					return nil, err
				}
				if containsResource(ft) || containsDomain(l, ft) {
					return nil, l.diag(f.Pos(), f.Name(), "records contain copied values, not resources")
				}
				field := Field{Name: name, GoName: f.Name(), Type: ft, Doc: l.docs[f.Pos()], Optional: optional}
				if value, ok := reflect.StructTag(st.Tag(i)).Lookup("wasmbinddefault"); ok {
					if !optional {
						return nil, l.diag(f.Pos(), f.Name(), "default requires optional field")
					}
					field.Default, err = l.fieldDefault(f, value)
					if err != nil {
						return nil, err
					}
				}
				d.Fields = append(d.Fields, field)
			}
			return out, nil
		}
		u, err := l.value(t.Underlying(), pos)
		if err != nil {
			return nil, err
		}
		u.Go = out.Go
		return u, nil
	case *types.Basic:
		kinds := map[types.BasicKind]string{types.Bool: "bool", types.String: "string", types.Int: "int", types.Uint: "uint", types.Int8: "int8", types.Uint8: "uint8", types.Int16: "int16", types.Uint16: "uint16", types.Int32: "int32", types.Uint32: "uint32", types.Int64: "int64", types.Uint64: "uint64", types.Float32: "float32", types.Float64: "float64"}
		if k := kinds[t.Kind()]; k != "" {
			out.Kind = k
			return out, nil
		}
	case *types.Slice:
		if b, ok := types.Unalias(t.Elem()).(*types.Basic); ok && b.Kind() == types.Uint8 {
			out.Kind = "bytes"
			return out, nil
		}
		out.Kind = "slice"
		e, err := l.value(t.Elem(), pos)
		out.Elem = e
		return out, err
	case *types.Array:
		out.Kind = "array"
		out.Length = t.Len()
		e, err := l.value(t.Elem(), pos)
		out.Elem = e
		return out, err
	case *types.Pointer:
		if n, ok := types.Unalias(t.Elem()).(*types.Named); ok {
			if d := l.named[n.Obj()]; d != nil {
				if d.Kind == "resource" {
					out.Kind = "resource"
					out.Name = d.Name
					return out, nil
				}
				out.Kind = "pointer"
				e, err := l.value(t.Elem(), pos)
				out.Elem = e
				return out, err
			}
		}
	}
	return nil, l.diag(pos, t.String(), "unsupported type "+t.String())
}
func containsResource(t *Type) bool {
	return t.Kind == "resource" || (t.Elem != nil && containsResource(t.Elem))
}

func specialization(s string) (string, []string, error) {
	i := strings.IndexByte(s, '[')
	if i < 0 {
		return s, nil, nil
	}
	expr, err := parser.ParseExpr("X" + s[i:])
	if err != nil {
		return "", nil, fmt.Errorf("invalid generic specialization %q", s)
	}
	var nodes []ast.Expr
	switch x := expr.(type) {
	case *ast.IndexExpr:
		nodes = []ast.Expr{x.Index}
	case *ast.IndexListExpr:
		nodes = x.Indices
	default:
		return "", nil, fmt.Errorf("invalid generic specialization %q", s)
	}
	var args []string
	for _, node := range nodes {
		var b bytes.Buffer
		format.Node(&b, token.NewFileSet(), node)
		args = append(args, b.String())
	}
	return s[:i], args, nil
}

