package generate

import (
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"strings"
)

// AdapterSource returns a self-contained standard-library adapter package.
func AdapterSource() ([]byte, error) {
	source, err := templates.ReadFile("templates/adapters.go.txt")
	if err != nil {
		return nil, err
	}
	formatted, err := format.Source(source)
	if err != nil {
		return nil, err
	}
	sum := sha256.Sum256(formatted)
	return append([]byte("// wasmbind adapters sha256: "+hex.EncodeToString(sum[:])+"\n"), formatted...), nil
}

// WriteAdapters writes a bindadapter companion package without dependencies.
// It refuses to replace unowned files or modified generated files.
func WriteAdapters(out string) (string, error) {
	source, err := AdapterSource()
	if err != nil {
		return "", err
	}
	path := filepath.Join(out, "adapters.go")
	info, err := os.Lstat(path)
	if err == nil && !info.Mode().IsRegular() {
		return "", fmt.Errorf("adapter output is not a regular file: %s", path)
	}
	previous, err := os.ReadFile(path)
	if err == nil {
		if bytes.Equal(source, previous) {
			return path, nil
		}
		line, payload, ok := bytes.Cut(previous, []byte("\n"))
		sum := sha256.Sum256(payload)
		if !ok || string(line) != "// wasmbind adapters sha256: "+hex.EncodeToString(sum[:]) || !strings.HasPrefix(string(payload), "// Code generated by wasmbind. DO NOT EDIT.\n") {
			return "", fmt.Errorf("modified or unowned adapter file: %s", path)
		}
		if err = os.WriteFile(path, source, 0644); err != nil {
			return "", err
		}
		return path, nil
	}
	if !os.IsNotExist(err) {
		return "", err
	}
	if err = os.MkdirAll(out, 0755); err != nil {
		return "", err
	}
	if err = os.WriteFile(path, source, 0644); err != nil {
		return "", err
	}
	return path, nil
}
